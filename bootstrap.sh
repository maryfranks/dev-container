#!/usr/bin/env bash
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
CONFIG_PATH="$REPO_DIR/config.toml"
CLI_PROFILE=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --profile=*) CLI_PROFILE="${1#*=}"; shift ;;
        --profile) [[ $# -ge 2 ]] || { echo "Error: --profile requires a value." >&2; exit 1; }; CLI_PROFILE="$2"; shift 2 ;;
        --config=*) CONFIG_PATH="${1#*=}"; shift ;;
        --config) [[ $# -ge 2 ]] || { echo "Error: --config requires a value." >&2; exit 1; }; CONFIG_PATH="$2"; shift 2 ;;
        -h|--help) echo "Usage: ./bootstrap.sh [--profile <name>] [--config <path>]"; exit 0 ;;
        *) echo "Error: Unknown argument: $1" >&2; exit 1 ;;
    esac
done

READ_ARGS=(--config "$CONFIG_PATH")
[[ -n "$CLI_PROFILE" ]] && READ_ARGS+=(--profile "$CLI_PROFILE")
config_eval="$(python3 -B "$REPO_DIR/scripts/read-config.py" "${READ_ARGS[@]}")"
eval "$config_eval"

expand_path() {
    case "$1" in
        "~") printf '%s\n' "$HOME" ;;
        "~/"*) printf '%s\n' "$HOME/${1:2}" ;;
        *) printf '%s\n' "$1" ;;
    esac
}

shell_single_quote() {
    printf "'%s'" "${1//\'/\'\\\'\'}"
}

sync_git_repo() {
    local repo_url="$1" dest_dir="$2"
    if [[ -d "$dest_dir/.git" ]]; then
        if git -C "$dest_dir" pull --ff-only >/dev/null 2>&1; then
            echo "[git]    Updated $dest_dir"
        else
            echo "[warn]   Could not fast-forward pull $dest_dir; continuing with existing checkout." >&2
        fi
        return 0
    fi
    if [[ -e "$dest_dir" || -L "$dest_dir" ]]; then
        if [[ -d "$dest_dir" && -z "$(ls -A "$dest_dir")" ]]; then
            rmdir "$dest_dir"
        else
            echo "Error: Destination '$dest_dir' already exists and is not a git repository for '$repo_url'." >&2
            exit 1
        fi
    fi
    mkdir -p "$(dirname "$dest_dir")"
    git clone "$repo_url" "$dest_dir"
    echo "[git]    Cloned $repo_url -> $dest_dir"
}

echo "==> Bootstrapping profile '$CFG_PROFILE' from $CFG_CONFIG_PATH"

EXTERNAL_DOTFILES_DIR=""
if [[ -n "$CFG_DOTFILES_REPO" || -n "$CFG_DOTFILES_DIR" ]]; then
    EXTERNAL_DOTFILES_DIR="${CFG_DOTFILES_DIR:+$(expand_path "$CFG_DOTFILES_DIR")}"
    EXTERNAL_DOTFILES_DIR="${EXTERNAL_DOTFILES_DIR:-$HOME/.local/share/devcontainer/dotfiles}"
    if [[ -n "$CFG_DOTFILES_REPO" ]]; then
        sync_git_repo "$CFG_DOTFILES_REPO" "$EXTERNAL_DOTFILES_DIR"
    elif [[ ! -d "$EXTERNAL_DOTFILES_DIR" ]]; then
        echo "Error: [sources].dotfiles_dir does not exist: $EXTERNAL_DOTFILES_DIR" >&2
        exit 1
    fi
fi

# Persist runtime exports outside the repo so `git status` stays clean
RUNTIME_FILE="$HOME/.config/devcontainer/runtime.zsh"
mkdir -p "$(dirname "$RUNTIME_FILE")"
{
    echo "# Generated by bootstrap.sh — do not edit manually."
    echo "export DEVCONTAINER_REPO_DIR=$(shell_single_quote "$REPO_DIR")"
    echo "export DEVCONTAINER_PROFILE=$(shell_single_quote "$CFG_PROFILE")"
    echo "export DEVCONTAINER_DOTFILES_DIR=$(shell_single_quote "$EXTERNAL_DOTFILES_DIR")"
    printf "DEVCONTAINER_MODULES_LANGUAGES=("
    for lang in "${CFG_MODULES_LANGUAGES[@]}"; do printf " %s" "$(shell_single_quote "$lang")"; done
    printf " )\nDEVCONTAINER_MODULES_TOOLS=("
    for tool in "${CFG_MODULES_TOOLS[@]}"; do printf " %s" "$(shell_single_quote "$tool")"; done
    printf " )\n"
    for ((i = 0; i < ${#CFG_ENV_KEYS[@]}; i++)); do
        [[ -n "${CFG_ENV_VALS[$i]}" ]] && echo "export ${CFG_ENV_KEYS[$i]}=$(shell_single_quote "${CFG_ENV_VALS[$i]}")"
    done
} >"$RUNTIME_FILE"
echo "[write]  $RUNTIME_FILE"

if [[ -n "$CFG_GIT_NAME" || -n "$CFG_GIT_EMAIL" ]]; then
    [[ -n "$CFG_GIT_NAME" ]] && git config --file "$HOME/.gitconfig.local" user.name "$CFG_GIT_NAME"
    [[ -n "$CFG_GIT_EMAIL" ]] && git config --file "$HOME/.gitconfig.local" user.email "$CFG_GIT_EMAIL"
    echo "[git]    Updated $HOME/.gitconfig.local identity for '$CFG_PROFILE'"
fi

SYMLINK_ARGS=(--config "$CFG_CONFIG_PATH" --profile "$CFG_PROFILE")
[[ -n "$EXTERNAL_DOTFILES_DIR" ]] && SYMLINK_ARGS+=(--dotfiles-dir "$EXTERNAL_DOTFILES_DIR")
"$REPO_DIR/scripts/symlinks.sh" "${SYMLINK_ARGS[@]}"
"$REPO_DIR/scripts/agents.sh" --config "$CFG_CONFIG_PATH" --profile "$CFG_PROFILE"

resolve_post_setup_script() {
    local expanded
    expanded="$(expand_path "$1")"
    if [[ "$expanded" == /* ]]; then
        [[ -f "$expanded" ]] && { printf '%s\n' "$expanded"; return 0; }
    elif [[ -n "$EXTERNAL_DOTFILES_DIR" && -f "$EXTERNAL_DOTFILES_DIR/$expanded" ]]; then
        printf '%s\n' "$EXTERNAL_DOTFILES_DIR/$expanded"; return 0
    elif [[ -f "$REPO_DIR/$expanded" ]]; then
        printf '%s\n' "$REPO_DIR/$expanded"; return 0
    fi
    echo "Error: [sources].post_setup_script not found: $1" >&2
    return 1
}

if [[ -n "$CFG_POST_SETUP_SCRIPT" ]]; then
    post_script="$(resolve_post_setup_script "$CFG_POST_SETUP_SCRIPT")"
    echo "==> Running follow-up script: $post_script"
    export DEVCONTAINER_REPO_DIR="$REPO_DIR" DEVCONTAINER_PROFILE="$CFG_PROFILE" DEVCONTAINER_DOTFILES_DIR="$EXTERNAL_DOTFILES_DIR"
    if [[ -x "$post_script" ]]; then "$post_script"; else bash "$post_script"; fi
fi

echo "==> Bootstrap complete (profile: $CFG_PROFILE)"
